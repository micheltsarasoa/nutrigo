// Writes docs/code-map.md: the exported names of each source file, one line per file.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const files = execFileSync(
  "git",
  [
    "ls-files",
    "--cached",
    "--others",
    "--exclude-standard",
    "apps",
    "packages",
  ],
  { encoding: "utf8" },
)
  .split("\n")
  .filter((f) => /\/src\/.*\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f));

const decl =
  /^export (?:default )?(?:async )?(?:function\*?|class|const|enum|type|interface)\s+(\w+)/gm;
const reexport = /^export (?:type )?\{([^}]*)\} from/gm;

const lines = files.flatMap((f) => {
  const src = readFileSync(f, "utf8");
  const names = [
    ...[...src.matchAll(decl)].map((m) => m[1]),
    ...[...src.matchAll(reexport)].flatMap((m) =>
      m[1].split(",").map((n) =>
        n
          .trim()
          .split(/\s+as\s+/)
          .pop(),
      ),
    ),
  ].filter(Boolean);
  return names.length ? [`- \`${f}\`: ${names.join(", ")}`] : [];
});

writeFileSync(
  "docs/code-map.md",
  `# Code map\n\nGenerated by \`npm run docs:map\` after each turn. Do not edit by hand.\n\n${lines.join("\n")}\n`,
);
